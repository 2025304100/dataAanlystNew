export function t(key: string): string {
  // 查找当前语言文案，回退到 en-US
  const value = I18N[currentLocale]?.[key] ?? I18N["en-US"]?.[key];
  if (value === undefined) {
    // 开发环境下对缺失 key 进行告警，便于发现遗漏的翻译条目
    if (import.meta.env.DEV) {
      console.warn(`[i18n] missing key: ${key}`);
    }
    return key;
  }
  return value;
}

